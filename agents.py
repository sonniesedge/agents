# fetch


def git(*args: str, cwd: Path | None = None) -> str:
    result = subprocess.run(
        ["git", *args], cwd=cwd, capture_output=True, text=True
    )
    if result.returncode != 0:
        raise RuntimeError((result.stderr or result.stdout).strip())
    return result.stdout.strip()


def fetch(cfg: Config) -> list[dict]:
    fetched: list[dict] = []
    if not cfg.sources:
        Out.say("no remote sources declared in config.yaml")
        return fetched
    for source in cfg.sources:
        dest = source.checkout
        action = "updated" if dest.exists() else "cloned"
        try:
            if dest.exists():
                Out.say(f"updating {source.slug}")
                git("fetch", "--tags", "--prune", "origin", cwd=dest)
            else:
                Out.say(f"cloning {source.slug}")
                dest.parent.mkdir(parents=True, exist_ok=True)
                git("clone", "--quiet", source.url, str(dest))

            ref = source.ref or git(
                "rev-parse", "--abbrev-ref", "origin/HEAD", cwd=dest
            ).split("/")[-1]
            # Prefer the remote-tracking branch so updates actually land.
            target = ref
            try:
                git("rev-parse", "--verify", f"origin/{ref}", cwd=dest)
                target = f"origin/{ref}"
            except RuntimeError:
                pass
            git("checkout", "--quiet", "--detach", target, cwd=dest)
            revision = git("rev-parse", "--short", "HEAD", cwd=dest)
            Out.say(f"  {source.slug} @ {revision}")
            fetched.append(
                {
                    "source": source.slug,
                    "owner": source.owner,
                    "action": action,
                    "revision": revision,
                }
            )
        except RuntimeError as exc:
            Out.warn(f"{source.slug}: {exc}")
            fetched.append(
                {
                    "source": source.slug,
                    "owner": source.owner,
                    "action": "failed",
                    "error": str(exc),
                }
            )
    return fetched


