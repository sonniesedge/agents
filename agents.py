def owned_by_repo(link: Path) -> bool:
    """True if `link` is a symlink pointing somewhere inside this repo."""
    if not link.is_symlink():
        return False
    target = Path(os.path.realpath(link))
    return target == REPO or REPO in target.parents


def relink(target_dir: Path, wanted: dict[str, Path]) -> dict[str, list[str]]:
    """Make target_dir contain exactly `wanted` among repo-owned symlinks."""
    target_dir.mkdir(parents=True, exist_ok=True)
    added: list[str] = []
    removed: list[str] = []

    for existing in sorted(target_dir.iterdir()):
        if owned_by_repo(existing) and existing.name not in wanted:
            existing.unlink()
            removed.append(existing.name)
            Out.say(f"  - {existing.name}")

    for name, src in sorted(wanted.items()):
        link = target_dir / name
        src = src.resolve()
        if link.is_symlink():
            if Path(os.path.realpath(link)) == src:
                continue
            if not owned_by_repo(link):
                Out.warn(f"{link} is a foreign symlink; leaving it alone")
                continue
            link.unlink()
        elif link.exists():
            Out.warn(f"{link} exists and is not a symlink; leaving it alone")
            continue
        link.symlink_to(src)
        added.append(name)
        Out.say(f"  + {name}")

    return {"added": added, "removed": removed}


def link_file(link: Path, src: Path | None) -> dict[str, list[str]]:
    """Point a single path at `src`, or remove it when `src` is None.

    Used for targets that are one file rather than a directory of entries,
    like opencode's global ~/.config/opencode/AGENTS.md.
    """
    if src is None or not src.exists():
        if owned_by_repo(link):
            link.unlink()
            Out.say(f"  - {link.name}")
            return {"added": [], "removed": [link.name]}
        return {"added": [], "removed": []}

    src = src.resolve()
    if link.is_symlink():
        if Path(os.path.realpath(link)) == src:
            return {"added": [], "removed": []}
        if not owned_by_repo(link):
            Out.warn(f"{link} is a foreign symlink; leaving it alone")
            return {"added": [], "removed": []}
        link.unlink()
    elif link.exists():
        Out.warn(f"{link} exists and is not a symlink; leaving it alone")
        return {"added": [], "removed": []}

    link.parent.mkdir(parents=True, exist_ok=True)
    link.symlink_to(src)
    Out.say(f"  + {link.name}")
    return {"added": [link.name], "removed": []}


def rule_files() -> list[Path]:
    """Themed rule files, in the order they are merged.

    An AGENTS.md here is the primary file, so it leads; the themed files
    follow alphabetically, which numeric prefixes can reorder.
    """
    src = REPO / "rules"
    if not src.is_dir():
        return []
    files = [f for f in sorted(src.glob("*.md")) if f.name != "README.md"]
    return sorted(files, key=lambda f: (f.name != MERGED_RULES, f.name))


def render_rules() -> Path | None:
    """Concatenate rules/*.md into one file, for `merge: true` targets.

    Each section is labelled with its source; Claude Code strips block-level
    HTML comments before loading, so the labels cost no context there.
    """
    out_dir = BUILD / "rules"
    out_dir.mkdir(parents=True, exist_ok=True)
    out = out_dir / MERGED_RULES

    files = rule_files()
    if not files:
        out.unlink(missing_ok=True)
        return None

    parts = [RULES_BANNER]
    for f in files:
        parts.append(f"<!-- {f.relative_to(REPO)} -->\n\n{f.read_text().strip()}")
    out.write_text("\n\n".join(parts) + "\n", encoding="utf-8")
    return out


def dir_entries(kind: str, built: Path) -> dict[str, Path]:
    """The set of entries a directory target of `kind` should contain."""
    if kind == "skills":
        return {d.name: d for d in sorted(built.iterdir()) if d.is_dir()}

    # subagents/, plugins/ and rules/ are named for their kind.
    src = REPO / kind
    if not src.is_dir():
        return {}
    markdown_only = kind in ("subagents", "rules")
    entries = sorted(src.glob("*.md")) if markdown_only else sorted(src.iterdir())
    # README.md documents the directory and examples/ demonstrates it;
    # neither is an artefact to install.
    return {
        f.name: f
        for f in entries
        if not f.name.startswith(".") and f.name not in ("README.md", "examples")
    }


def file_source(tool: str, kind: str, target: Path) -> Path:
    """The repo file a single-file target should point at.

    `config` is per-tool, read from settings/<tool>/ — tool config filenames
    are generic enough to collide (settings.json, config.toml) so they are
    kept in separate directories.
    """
    return REPO / "settings" / tool / target.name


def prune_stale_targets(cfg: Config) -> list[str]:
    """Clean up targets this repo linked before but no longer declares.

    Retargeting — including switching `rules` between a directory and a
    concatenated file — would otherwise leave the old location populated. For
    rules that is not merely untidy: the old directory would still be globbed
    and every rule would load twice.
    """
    record = BUILD / "linked.json"
    current = {str(t.path) for kinds in cfg.targets.values() for t in kinds.values()}

    previous: set[str] = set()
    if record.exists():
        try:
            previous = set(json.loads(record.read_text()))
        except (json.JSONDecodeError, TypeError):
            pass

    pruned: list[str] = []
    for stale in sorted(previous - current):
        path = Path(stale)
        if owned_by_repo(path):
            path.unlink()
            pruned.append(str(path))
            Out.say(f"  - {path} (no longer a target)")
        elif path.is_dir():
            for entry in sorted(path.iterdir()):
                if owned_by_repo(entry):
                    entry.unlink()
                    pruned.append(str(entry))
                    Out.say(f"  - {entry} (no longer a target)")
            if not any(path.iterdir()):
                path.rmdir()

    record.parent.mkdir(parents=True, exist_ok=True)
    record.write_text(json.dumps(sorted(current), indent=2) + "\n")
    return pruned


def link(cfg: Config, built: Path) -> dict:
    result: dict = {"pruned": prune_stale_targets(cfg), "targets": []}
    for tool, kinds in cfg.targets.items():
        for kind, target in kinds.items():
            Out.say(f"linking {tool}.{kind} -> {target.path}")
            if kind == "rules" and target.merge:
                merged = render_rules()
                if target.is_file:
                    changed = link_file(target.path, merged)
                else:
                    # Through relink, so any per-file symlinks left by a
                    # previous merge: false are cleared from the directory.
                    changed = relink(
                        target.path, {MERGED_RULES: merged} if merged else {}
                    )
            elif kind in FILE_KINDS:
                changed = link_file(target.path, file_source(tool, kind, target.path))
            else:
                changed = relink(target.path, dir_entries(kind, built))
            result["targets"].append(
                {"tool": tool, "kind": kind, "path": str(target.path), **changed}
            )
        check_rules_wiring(tool, kinds)
    return result


# Tools that do not read a rules directory on their own and need to be
# pointed at it from their config. Claude Code reads ~/.claude/rules/
# natively, so it is absent here.
NEEDS_RULES_WIRING = {"opencode": "instructions"}


def check_rules_wiring(tool: str, kinds: dict[str, Target]) -> None:
    """Warn when linked rules are not actually loaded.

    opencode only reads a rules *directory* if its config globs it. That
    config is gitignored, so a fresh clone can end up with rules linked but
    silently never loaded — the one failure this target cannot detect itself.

    Merging into a directory still needs the glob: opencode reads AGENTS.md
    natively only at the top of its config directory, not inside a subfolder.
    """
    key = NEEDS_RULES_WIRING.get(tool)
    if key is None or "rules" not in kinds:
        return

    rules = kinds["rules"]
    if rules.is_file:
        return

    config = kinds.get("config")
    if config is None:
        Out.warn(
            f"{tool}: rules are linked to {rules.path} but {tool} has no "
            f"`config` target, so nothing can point `{key}` at them."
        )
        return

    source = file_source(tool, "config", config.path)
    if not source.exists():
        Out.warn(f"{tool}: {source} is missing; `{key}` cannot glob {rules.path}.")
        return

    # Match on the directory, so any glob shape inside it counts.
    home = str(Path.home())
    text = source.read_text(encoding="utf-8")
    needle = str(rules.path)
    if needle not in text and needle.replace(home, "~") not in text:
        Out.warn(
            f"{tool}: rules are linked to {rules.path} but {source.name} does "
            f"not glob them, so they will not load. Add to `{key}`:\n"
            f'    "{needle.replace(home, "~")}/*.md"'
        )


