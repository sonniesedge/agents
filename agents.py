COMMAND_HELP = {
    "sync": "fetch remote sources, rebuild, and refresh symlinks",
    "fetch": "clone or update remote sources only",
    "build": "render .build/ only",
    "link": "refresh symlinks only",
    "list": "list every resolvable skill and where it came from",
    "status": "show what is installed, and from which source",
    "unlink": "remove every symlink this repo owns",
}


def global_flags(suppress: bool) -> argparse.ArgumentParser:
    """The flags accepted both before and after the command.

    The copies attached to subcommands default to SUPPRESS so that they do
    not overwrite a value already given ahead of the command — otherwise
    `--json sync` would be silently reset by the subparser's own default.
    """
    parser = argparse.ArgumentParser(add_help=False)
    default = argparse.SUPPRESS if suppress else False
    parser.add_argument(
        "-q",
        "--quiet",
        action="store_true",
        default=default,
        help="only print warnings and errors",
    )
    parser.add_argument(
        "--json",
        action="store_true",
        default=default,
        help="print the result as JSON instead of text",
    )
    return parser


def main() -> None:
    parser = argparse.ArgumentParser(
        prog="agents.py",
        description="Manage user-scoped agent skills, agent files, and plugins.",
        epilog=(
            "Every command is safe to re-run, and only ever touches symlinks\n"
            "that point back into this repo. Anything else is left alone."
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
        parents=[global_flags(suppress=False)],
    )
    # So every command can read it, not just the one that defines the flag.
    parser.set_defaults(no_fetch=False)

    shared = global_flags(suppress=True)
    sub = parser.add_subparsers(dest="command", metavar="command")
    for name, cmd_help in COMMAND_HELP.items():
        p = sub.add_parser(
            name, help=cmd_help, description=cmd_help, parents=[shared]
        )
        if name == "sync":
            p.add_argument(
                "--no-fetch",
                action="store_true",
                help="skip updating remote sources, and do not touch the network",
            )

    args = parser.parse_args()
    Out.quiet = args.quiet
    Out.json = args.json

    # No command: point at sync rather than running it. sync reaches the
    # network and rewrites symlinks, so it should be asked for.
    if not args.command:
        if args.json:
            print(json.dumps({"ok": False, "error": "no command given"}, indent=2))
            sys.exit(1)
        parser.print_help()
        print(
            "\nMost of the time you want:\n"
            "    ./agents.py sync\n"
            "which updates remote sources, rebuilds, and refreshes every symlink."
        )
        return

    result = COMMANDS[args.command](load_config(), args)
    if args.json:
        # Warnings go into the document rather than stderr, so a single
        # parse sees everything that happened.
        print(
            json.dumps(
                {"ok": True, "command": args.command, **result,
                 "warnings": Out.warnings},
                indent=2,
            )
        )


if __name__ == "__main__":
    main()
