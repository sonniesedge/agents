#!/usr/bin/env python3
"""Manage user-scoped agent skills, agent files, and plugins.

Locally-authored skills live unprefixed under skills/. Remote skills are
cloned into .vendor/ from the sources declared in config.yaml. Both are
rendered into .build/skills/<owner>-<name>/ with a frontmatter `name` that
matches the directory, per the Agent Skills spec (agentskills.io), and then
symlinked into the per-tool targets declared in config.yaml.

Usage:
    ./agents.py sync            fetch + build + link (the everyday command)
    ./agents.py fetch           clone/update remote sources only
    ./agents.py build           render .build/ only
    ./agents.py link            refresh symlinks only
    ./agents.py status          show what is installed and where it came from
    ./agents.py list            list every resolvable skill
    ./agents.py unlink          remove every symlink this repo owns
"""

from __future__ import annotations

import argparse
import fnmatch
import json
import os
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass, field
from typing import NoReturn
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover
    sys.exit("PyYAML is required: pip install pyyaml")

REPO = Path(__file__).resolve().parent
VENDOR = REPO / ".vendor"
BUILD = REPO / ".build"
SKILL_FILE = "SKILL.md"
# Kinds a tool may declare a target for.
DIR_KINDS = ("skills", "subagents", "plugins")
FILE_KINDS = ("config",)
# `rules` takes a directory of themed files, optionally merged into one.
DUAL_KINDS = ("rules",)
KINDS = DIR_KINDS + FILE_KINDS + DUAL_KINDS
MERGED_RULES = "AGENTS.md"
RULES_BANNER = (
    "<!-- Generated by agents.py from rules/*.md — do not edit here. -->"
)
FRONTMATTER = re.compile(r"\A---\r?\n(.*?)\r?\n---[ \t]*\r?\n?", re.DOTALL)
NAME_LINE = re.compile(r"^name:.*$", re.MULTILINE)


# --------------------------------------------------------------------------
# output


class Out:
    quiet = False
    json = False
    warnings: list[str] = []

    @staticmethod
    def say(msg: str) -> None:
        if not (Out.quiet or Out.json):
            print(msg)

    @staticmethod
    def warn(msg: str) -> None:
        Out.warnings.append(msg)
        if not Out.json:
            print(f"warning: {msg}", file=sys.stderr)

    @staticmethod
    def die(msg: str) -> NoReturn:
        if Out.json:
            print(json.dumps({"ok": False, "error": msg}, indent=2))
            sys.exit(1)
        sys.exit(f"error: {msg}")


