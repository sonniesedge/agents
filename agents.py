def split_git_url(url: str) -> list[str]:
    """Break a git URL into its path segments, host first.

    Handles the three shapes git accepts:
        https://github.com/org/repo.git  -> [github.com, org, repo]
        git@github.com:org/repo.git      -> [github.com, org, repo]
        ssh://git@github.com/org/repo    -> [github.com, org, repo]
    """
    body = url.strip()
    for prefix in ("https://", "http://", "ssh://", "git+ssh://"):
        body = body.removeprefix(prefix)
    body = body.split("@", 1)[-1]  # drop any user@ portion
    body = body.replace(":", "/").removesuffix(".git")
    return [p for p in body.split("/") if p and p not in (".", "..")]


@dataclass
class Source:
    owner: str
    repo: str
    ref: str | None = None
    # Subdirectories to scan. An entry reading "not <path>" excludes instead.
    paths: list[str] = field(default_factory=list)

    @property
    def url(self) -> str:
        if "://" in self.repo or self.repo.startswith("git@"):
            return self.repo
        return f"https://github.com/{self.repo}.git"

    @property
    def slug(self) -> str:
        """Filesystem-safe identity for this source inside .vendor/."""
        return "/".join(split_git_url(self.url))

    @property
    def checkout(self) -> Path:
        return VENDOR / self.slug

    @property
    def includes(self) -> list[str]:
        """Subdirectories to scan; the repo root when none are given."""
        return [p for p in self.paths if not is_negated(p)] or [""]

    @property
    def excludes(self) -> list[str]:
        return [p.split(None, 1)[1].strip("/") for p in self.paths if is_negated(p)]

    def wants(self, relative: str) -> bool:
        """Whether a skill at `relative` (posix, from the checkout) is kept."""
        return not any(path_matches(relative, pat) for pat in self.excludes)


def is_negated(entry: str) -> bool:
    """True for a path written as `not <path>`."""
    head, _, rest = entry.partition(" ")
    return head == "not" and bool(rest.strip())


def path_matches(relative: str, pattern: str) -> bool:
    """True if `relative`, or any directory above it, matches `pattern`.

    So "skills/deprecated" excludes everything beneath it, and a glob like
    "skills/*.archived" excludes each directory it matches.
    """
    if relative == pattern or relative.startswith(f"{pattern}/"):
        return True
    parts = relative.split("/")
    return any(
        fnmatch.fnmatch("/".join(parts[:i]), pattern)
        for i in range(1, len(parts) + 1)
    )


@dataclass
class Target:
    """Where one kind of artefact is installed, and how.

    `merge` applies to `rules` only: false links each themed file, true
    concatenates them into a single generated file.
    """

    path: Path
    merge: bool = False

    @property
    def is_file(self) -> bool:
        """True when the path names a file rather than a directory."""
        return self.path.suffix == ".md"

    @property
    def merged_path(self) -> Path:
        """Where the concatenated file lands when merging."""
        return self.path if self.is_file else self.path / MERGED_RULES


@dataclass
class Config:
    owner: str
    owner_from: str  # how `owner` was resolved, for `status`
    targets: dict[str, dict[str, Target]]  # tool -> kind -> target
    sources: list[Source]


def expand(raw: str) -> Path:
    return Path(os.path.expandvars(str(raw))).expanduser()


def derive_owner(remote: str) -> tuple[str, str]:
    """Infer the owner prefix from this repo's own git remote.

    Returns (owner, explanation). Exits with guidance if it cannot be found,
    because guessing here would rename every skill you author.
    """
    hint = (
        f"Set `owner:` explicitly in config.yaml, or add the remote:\n"
        f"    git remote add {remote} git@github.com:<org>/<repo>.git"
    )
    try:
        url = git("remote", "get-url", remote, cwd=REPO)
    except RuntimeError:
        Out.die(f"owner is `auto` but this repo has no '{remote}' remote.\n{hint}")

    parts = split_git_url(url)
    if len(parts) < 3:
        Out.die(f"owner is `auto` but could not parse an org from '{url}'.\n{hint}")
    return parts[-2], f"auto, from {remote} ({url})"


CONFIG_FILE = "config.yaml"
LOCAL_CONFIG_FILE = "config.local.yaml"
RETIRED = ("agents.yaml", "skills.yaml", "skills.local.yaml")


BANG_NEGATION = re.compile(r"^\s*-\s+!+\s*(?P<path>\S.*?)\s*$", re.MULTILINE)


def check_bang_negation(filename: str, text: str) -> None:
    """Reject `- ! path`, which YAML would quietly turn into an inclusion.

    A leading `!` is a YAML tag. Followed by a space the tag is
    non-specific and is discarded, so `- ! skills/deprecated` parses as
    plain `skills/deprecated` — an exclusion inverted into an inclusion,
    with nothing to notice at runtime. Without the space it is a hard parse
    error. Negation is written `not <path>` here for exactly this reason.
    """
    for match in BANG_NEGATION.finditer(text):
        found = match.group("path").strip("'\"")
        Out.die(
            f"{filename}: `- ! {found}` is not how exclusions are written, and "
            f"YAML would drop the `!` and include the path instead. Use:\n"
            f"    - not {found}"
        )


def load_config() -> Config:
    main = REPO / CONFIG_FILE
    if not main.exists():
        stale = [f for f in RETIRED if (REPO / f).exists()]
        hint = (
            f"\nFound {', '.join(stale)}: these merged into {CONFIG_FILE}."
            if stale
            else ""
        )
        Out.die(f"missing {main}{hint}")

    # config.local.yaml is gitignored: somewhere to keep private or
    # work-internal settings without publishing them. Scalar keys override,
    # `sources` accumulate.
    layers: list[tuple[str, dict]] = []
    for path in (main, REPO / LOCAL_CONFIG_FILE):
        if path.exists():
            text = path.read_text()
            check_bang_negation(path.name, text)
            layers.append((path.name, yaml.safe_load(text) or {}))

    data: dict = {}
    for _, layer in layers:
        data.update(layer)

    raw_owner = data.get("owner")
    if raw_owner is None or str(raw_owner).strip().lower() in ("auto", ""):
        owner, owner_from = derive_owner(str(data.get("owner_remote") or "origin"))
    else:
        owner, owner_from = str(raw_owner).strip(), CONFIG_FILE

    targets: dict[str, dict[str, Target]] = {}
    raw_targets = data.get("targets") or {}
    if any(not isinstance(v, dict) for v in raw_targets.values()):
        Out.die(
            "targets must be grouped by tool, e.g.\n"
            "    targets:\n"
            "      opencode:\n"
            "        skills: ~/.config/opencode/skill"
        )
    for tool, kinds in raw_targets.items():
        parsed: dict[str, Target] = {}
        for kind, value in kinds.items():
            where = f"{CONFIG_FILE}: `{tool}.{kind}`"
            if kind == "agents":
                Out.die(
                    f"{where} was renamed to `subagents`, and the directory it "
                    f"installs from is now subagents/.\nRename the key; the path "
                    f"it points at does not change."
                )
            if kind not in KINDS:
                Out.die(
                    f"{where} is not a recognised target. "
                    f"Expected one of: {', '.join(KINDS)}"
                )
            # A bare string is shorthand for `path`.
            if not isinstance(value, dict):
                parsed[kind] = Target(path=expand(value))
                continue

            unknown = set(value) - {"path", "merge"}
            if unknown:
                Out.die(f"{where} has unknown key(s): {', '.join(sorted(unknown))}")
            if not value.get("path"):
                Out.die(f"{where} needs a `path`")
            if "merge" in value and kind not in DUAL_KINDS:
                Out.die(f"{where} does not support `merge`")
            parsed[kind] = Target(
                path=expand(value["path"]), merge=bool(value.get("merge", False))
            )

        rules = parsed.get("rules")
        if rules and rules.is_file and not rules.merge:
            Out.die(
                f"{CONFIG_FILE}: `{tool}.rules.path` names a file "
                f"({rules.path.name}) but `merge` is false, so there are many "
                f"files to install and one place to put them.\n"
                f"Set `merge: true`, or point `path` at a directory."
            )
        targets[str(tool)] = parsed
    if not targets:
        Out.die(f"{CONFIG_FILE} must declare at least one tool under `targets`")

    sources = []
    for name, layer in layers:
        for i, entry in enumerate(layer.get("sources") or []):
            where = f"{name} source #{i + 1}"
            src_repo = entry.get("repo")
            if not src_repo:
                Out.die(f"{where} needs a `repo`")

            # Default the prefix to the org the repo belongs to, so
            # mattpocock/skills yields "mattpocock".
            src_owner = entry.get("owner")
            if not src_owner:
                parts = split_git_url(Source(owner="", repo=str(src_repo)).url)
                if len(parts) < 3:
                    Out.die(
                        f"{where}: could not read an owner from "
                        f"'{src_repo}'. Set `owner` explicitly."
                    )
                src_owner = parts[-2]

            retired = {"include", "exclude"} & set(entry)
            if retired:
                Out.die(
                    f"{where} uses `{'`, `'.join(sorted(retired))}`, which "
                    f"`path` replaced. Select by location instead:\n"
                    f"    path:\n"
                    f"      - skills\n"
                    f"      - not skills/deprecated"
                )

            raw = entry.get("path") or []
            paths = [raw] if isinstance(raw, str) else list(raw)
            sources.append(
                Source(
                    owner=str(src_owner),
                    repo=str(src_repo),
                    ref=entry.get("ref"),
                    paths=[str(p).strip().strip("/") for p in paths if str(p).strip()],
                )
            )
    return Config(
        owner=owner, owner_from=owner_from, targets=targets, sources=sources
    )


